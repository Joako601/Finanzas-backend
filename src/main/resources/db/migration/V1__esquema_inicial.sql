-- Esquema inicial del backend de Finanzas (PostgreSQL 16 / compatible con H2 MODE=PostgreSQL).
-- Regla de privacidad (D-020): nunca se almacenan movimientos, saldos ni deudas personales en texto plano.

CREATE TABLE usuario_perfil (
    firebase_uid VARCHAR(128) PRIMARY KEY,
    correo VARCHAR(254) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'USER',
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_usuario_rol CHECK (rol IN ('USER', 'ADMIN'))
);

CREATE INDEX idx_usuario_perfil_correo ON usuario_perfil (correo);

CREATE TABLE producto_financiero (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    categoria VARCHAR(60) NOT NULL,
    entidad VARCHAR(80) NOT NULL,
    costo_referencia_pesos BIGINT NOT NULL DEFAULT 0,
    periodicidad VARCHAR(40) NOT NULL,
    tasa_anual_referencia NUMERIC(6, 2),
    detalle_referencia VARCHAR(280) NOT NULL,
    fuente_referencia VARCHAR(160) NOT NULL,
    image_url VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    activo_unico BOOLEAN DEFAULT TRUE,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_producto_activo_nombre_entidad UNIQUE (nombre, entidad, activo_unico),
    CONSTRAINT chk_producto_activo_unico CHECK (
        (activo = TRUE AND activo_unico = TRUE) OR (activo = FALSE AND activo_unico IS NULL)
    ),
    CONSTRAINT chk_producto_costo_no_negativo CHECK (costo_referencia_pesos >= 0),
    CONSTRAINT chk_producto_tasa_valida CHECK (
        tasa_anual_referencia IS NULL OR (tasa_anual_referencia >= 0 AND tasa_anual_referencia <= 500)
    )
);

CREATE INDEX idx_producto_financiero_activo_categoria ON producto_financiero (activo, categoria);

CREATE TABLE usuario_favorito (
    firebase_uid VARCHAR(128) NOT NULL,
    producto_id BIGINT NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (firebase_uid, producto_id),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (firebase_uid) REFERENCES usuario_perfil (firebase_uid) ON DELETE CASCADE,
    CONSTRAINT fk_favorito_producto FOREIGN KEY (producto_id) REFERENCES producto_financiero (id) ON DELETE CASCADE
);

CREATE INDEX idx_usuario_favorito_producto ON usuario_favorito (producto_id);

CREATE TABLE tipo_cambio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moneda_base VARCHAR(3) NOT NULL,
    moneda_destino VARCHAR(3) NOT NULL,
    fecha DATE NOT NULL,
    tasa NUMERIC(14, 6) NOT NULL,
    fuente VARCHAR(80) NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tipo_cambio_par_fecha_fuente UNIQUE (moneda_base, moneda_destino, fecha, fuente),
    CONSTRAINT chk_tipo_cambio_tasa_positiva CHECK (tasa > 0),
    CONSTRAINT chk_tipo_cambio_monedas_distintas CHECK (moneda_base <> moneda_destino),
    CONSTRAINT chk_tipo_cambio_monedas_iso CHECK (
        CHAR_LENGTH(moneda_base) = 3 AND moneda_base = UPPER(moneda_base)
        AND CHAR_LENGTH(moneda_destino) = 3 AND moneda_destino = UPPER(moneda_destino)
    )
);

CREATE INDEX idx_tipo_cambio_par_fecha ON tipo_cambio (moneda_base, moneda_destino, fecha DESC);

CREATE TABLE indicador_economico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave VARCHAR(40) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    valor NUMERIC(14, 6) NOT NULL,
    unidad VARCHAR(30) NOT NULL,
    fecha DATE NOT NULL,
    fuente VARCHAR(80) NOT NULL,
    serie_externa VARCHAR(30),
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_indicador_clave_fecha UNIQUE (clave, fecha)
);

CREATE TABLE dia_inhabil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    nombre VARCHAR(140) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    anio INT NOT NULL,
    fuente VARCHAR(80) NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_dia_inhabil_fecha_tipo UNIQUE (fecha, tipo),
    CONSTRAINT chk_dia_inhabil_tipo CHECK (tipo IN ('OFICIAL_MX', 'BANCARIO_CNBV')),
    CONSTRAINT chk_dia_inhabil_anio CHECK (anio BETWEEN 2000 AND 2100)
);

CREATE INDEX idx_dia_inhabil_anio ON dia_inhabil (anio);

-- Bóveda Zero-Knowledge opcional: almacena únicamente el archivo .respaldo ya cifrado con AES-256-GCM en el teléfono.
-- Nota JPA: mapear contenido_cifrado como byte[] sin @Lob para compatibilidad con Hibernate + PostgreSQL BYTEA.
CREATE TABLE respaldo_cifrado (
    firebase_uid VARCHAR(128) PRIMARY KEY,
    contenido_cifrado BYTEA NOT NULL,
    tamano_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    version_esquema INT NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_respaldo_usuario FOREIGN KEY (firebase_uid) REFERENCES usuario_perfil (firebase_uid) ON DELETE CASCADE,
    CONSTRAINT chk_respaldo_tamano_valido CHECK (tamano_bytes > 0 AND tamano_bytes <= 15728640),
    CONSTRAINT chk_respaldo_sha256_largo CHECK (CHAR_LENGTH(sha256) = 64),
    CONSTRAINT chk_respaldo_version_positiva CHECK (version_esquema > 0)
);
